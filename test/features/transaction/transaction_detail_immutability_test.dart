import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:mocktail/mocktail.dart';
import 'package:multi_wallet_tracker/core/theme/app_theme.dart';
import 'package:multi_wallet_tracker/features/transaction/domain/entities/transaction_record.dart';
import 'package:multi_wallet_tracker/features/transaction/domain/usecases/get_transaction_detail.dart';
import 'package:multi_wallet_tracker/features/transaction/presentation/screens/transaction_detail_screen.dart';

import '../../helpers/transaction_test_helpers.dart';
import '../../helpers/wallet_test_helpers.dart';

void main() {
  late MockTransactionRepository transactions;
  late MockWalletRepository wallets;
  late MockCategoryRepository categories;

  setUp(() {
    transactions = MockTransactionRepository();
    wallets = MockWalletRepository();
    categories = MockCategoryRepository();
  });

  GetTransactionDetail loader() => GetTransactionDetail(
        transactions: transactions,
        wallets: wallets,
        categories: categories,
      );

  Future<void> pumpDetail(
    WidgetTester tester,
    TransactionRecord record,
  ) async {
    when(() => transactions.byId(record.id)).thenAnswer((_) async => record);
    when(() => wallets.byId(record.sourceWalletId))
        .thenAnswer((_) async => walletFixture());
    when(() => categories.byId(record.categoryId!))
        .thenAnswer((_) async => categoryFixture());

    await tester.pumpWidget(
      MaterialApp(
        theme: AppTheme.light,
        home: TransactionDetailScreen(
          transactionId: record.id,
          loader: loader(),
        ),
      ),
    );
    await tester.pumpAndSettle();
  }

  testWidgets('subscription charges hide edit and delete actions',
      (WidgetTester tester) async {
    await pumpDetail(
      tester,
      recordFixture(
        subscriptionId: 'sub-1',
        billingPeriod: '2026-11-01',
      ),
    );

    expect(find.text('Generated by a subscription'), findsOneWidget);
    expect(
      find.textContaining('cannot be edited or deleted'),
      findsOneWidget,
    );
    expect(find.byTooltip('Edit transaction'), findsNothing);
    expect(find.byTooltip('Delete transaction'), findsNothing);
  });

  testWidgets('manual transactions keep edit and delete actions',
      (WidgetTester tester) async {
    await pumpDetail(tester, recordFixture());

    expect(find.text('Generated by a subscription'), findsNothing);
    expect(find.byTooltip('Edit transaction'), findsOneWidget);
    expect(find.byTooltip('Delete transaction'), findsOneWidget);
  });

  testWidgets('subscription charge notice survives 2.0x text scaling',
      (WidgetTester tester) async {
    final TransactionRecord record = recordFixture(
      subscriptionId: 'sub-1',
      billingPeriod: '2026-11-01',
    );
    when(() => transactions.byId(record.id)).thenAnswer((_) async => record);
    when(() => wallets.byId(record.sourceWalletId))
        .thenAnswer((_) async => walletFixture());
    when(() => categories.byId(record.categoryId!))
        .thenAnswer((_) async => categoryFixture());

    await tester.pumpWidget(
      MaterialApp(
        theme: AppTheme.dark,
        home: Builder(
          builder: (BuildContext context) => MediaQuery(
            data: MediaQuery.of(context).copyWith(
              textScaler: const TextScaler.linear(2),
            ),
            child: TransactionDetailScreen(
              transactionId: record.id,
              loader: loader(),
            ),
          ),
        ),
      ),
    );
    await tester.pumpAndSettle();

    expect(tester.takeException(), isNull);
    expect(find.text('Generated by a subscription'), findsOneWidget);
  });
}
